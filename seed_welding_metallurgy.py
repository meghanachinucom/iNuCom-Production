def seed_welding_metallurgy(db) -> int:
    """
    Idempotently seed the 'Welding Metallurgy' project (Comp & Motion Graphics only).
    Only '3D Comp' (Yet to Start) and 'Motion Graphics' (Locked) stages are created
    for each scene file so no other teams are involved.
    Returns number of newly inserted scene files.
    """
    proj = db.execute(
        "SELECT id FROM projects WHERE LOWER(name) = 'welding metallurgy'"
    ).fetchone()
    if proj:
        proj_id = proj["id"]
    else:
        cur = db.execute(
            """
            INSERT INTO projects (name, description, project_type, status)
            VALUES ('Welding Metallurgy', 'Comp & Motion Graphics Only Project', 'Comp Only', 'Active')
            """
        )
        proj_id = cur.lastrowid

    # Check if already seeded
    existing_count = db.execute(
        """
        SELECT COUNT(*) FROM files f
        JOIN chapters c ON f.chapter_id = c.id
        WHERE c.project_id = ?
        """,
        (proj_id,),
    ).fetchone()[0]
    if existing_count >= len(WELDING_METALLURGY_SCENES):
        return 0

    chapter_cache: dict[str, int] = {}
    existing_names = {
        r[0].lower()
        for r in db.execute(
            "SELECT f.name FROM files f JOIN chapters c ON f.chapter_id = c.id WHERE c.project_id = ?",
            (proj_id,),
        ).fetchall()
    }

    inserted = 0
    for scene_name in WELDING_METALLURGY_SCENES:
        clean_name = scene_name.strip()
        if not clean_name or clean_name.lower() in existing_names:
            continue
        existing_names.add(clean_name.lower())

        prefix = clean_name.split("_", 1)[0]
        chap_name = CHAPTER_TITLES.get(prefix, f"{prefix} - Scenes")

        if chap_name not in chapter_cache:
            c_row = db.execute(
                "SELECT id FROM chapters WHERE project_id = ? AND name = ?",
                (proj_id, chap_name),
            ).fetchone()
            if c_row:
                chapter_cache[chap_name] = c_row["id"]
            else:
                cur_c = db.execute(
                    "INSERT INTO chapters (project_id, name, description, status) VALUES (?, ?, ?, 'Active')",
                    (proj_id, chap_name, f"Welding Metallurgy - {chap_name}"),
                )
                chapter_cache[chap_name] = cur_c.lastrowid

        chap_id = chapter_cache[chap_name]
        cur_f = db.execute(
            """
            INSERT INTO files (chapter_id, name, file_type, complexity, status, take_count)
            VALUES (?, ?, 'Scene', 'Medium', 'Yet to Start', 0)
            """,
            (chap_id, clean_name),
        )
        file_id = cur_f.lastrowid

        # Comp-only pipeline: ONLY 3D Comp (Yet to Start) and Motion Graphics (Locked)
        db.execute(
            """
            INSERT INTO file_pipeline (file_id, step_name, stage_order, team_name, status, take_count)
            VALUES (?, '3D Comp', 10, '3D Comp & Motion Graphics', 'Yet to Start', 0)
            """,
            (file_id,),
        )
        db.execute(
            """
            INSERT INTO file_pipeline (file_id, step_name, stage_order, team_name, status, take_count)
            VALUES (?, 'Motion Graphics', 11, '3D Comp & Motion Graphics', 'Locked', 0)
            """,
            (file_id,),
        )
        inserted += 1

    if inserted:
        db.execute(
            "INSERT INTO activity_log (action, details) VALUES ('Project Seeded', ?)",
            (f"Seeded Welding Metallurgy (Comp Only) with {inserted} scene files.",),
        )
    db.commit()
    return inserted
